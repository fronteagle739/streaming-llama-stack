"""Regenerate a native relayout from an archived original container, without a copy.

Every generated payload byte and header is compared with the target while a
whole-file SHA256 is calculated. This proves relayout reproducibility from the
specified archive, not raw-checkpoint-only reproduction of inherited auxiliaries.
Run under an explicit host-memory budget and the caller's disk-priority admission.
"""
from __future__ import annotations
import argparse
import datetime
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from scripts.dsv41_fp4_layout import pack_nvfp4_blob
from scripts.slpack import MAGIC,VERSION,ModelFile
from scripts.pack_slpack import BLOB,native_descriptor

CHUNK=4<<20
LAYERS=48
EXPERTS=512


def identity(path):
    stat=path.stat()
    return {name:getattr(stat,name) for name in ('st_dev','st_ino','st_size','st_mtime_ns','st_ctime_ns')}


def plan(source):
    pack=ModelFile(source,allow_legacy=True)
    rows=[dict(name=name,offset=row[0],bytes=row[1],sha256=row[2].hex()) for name,row in pack.sections.items()]
    if pack.sections['experts'][1]!=LAYERS*EXPERTS*BLOB:
        raise ValueError('Original QFN expert geometry differs')
    for name in ('meta','experts.layout'):
        if not pack.verify(name):
            raise ValueError('Original auxiliary SHA differs: '+name)
    layout=pack.read('experts.layout').decode('utf8')
    if not layout.splitlines()[0].startswith('# experts v6:') or [list(map(int,row.split())) for row in layout.splitlines()[1:] if row.strip()] != [
            [layer,40,40,layer*EXPERTS*BLOB,BLOB] for layer in range(LAYERS)]:
        raise ValueError('Expected original v6 NVFP4 layout')
    meta=json.loads(pack.read('meta'))
    if 'qfn_native_nvfp4' in meta:
        raise ValueError('Source already has native metadata')
    meta['qfn_native_nvfp4']=native_descriptor(layout)
    replacements={'meta':(json.dumps(meta,ensure_ascii=False,separators=(',',':'),allow_nan=False)+'\n').encode(),
                  'experts.layout':('# experts v7 '+native_descriptor(layout)['layout']+'\n'+'\n'.join(layout.splitlines()[1:])+'\n').encode()}
    planned=[]
    for index,row in enumerate(rows):
        new=dict(row)
        if row['name'] in replacements:
            data=replacements[row['name']]
            if index+1<len(rows) and row['offset']+len(data)>rows[index+1]['offset']:
                raise ValueError('Replacement exceeds reserved section gap')
            new.update(bytes=len(data),sha256=hashlib.sha256(data).hexdigest())
        planned.append(new)
    with source.open('rb') as stream:
        raw=stream.read(2<<20)
    return dict(source_sections=rows,target_sections=planned,target_bytes=planned[-1]['offset']+planned[-1]['bytes']),raw,replacements


def verify(source,target,progress=lambda message:None):
    before_source,before_target=identity(source),identity(target)
    info,raw,replacements=plan(source)
    if target.stat().st_size!=info['target_bytes']:
        raise ValueError('Target size differs from relayout plan')
    full=hashlib.sha256()
    generated=[]
    with source.open('rb') as src,target.open('rb') as dst:
        actual_header=dst.read(len(raw));full.update(actual_header)
        previous=len(raw)
        for row,new in zip(info['source_sections'],info['target_sections']):
            # The deterministic writer zero-fills every section alignment gap.
            gap=row['offset']-previous
            while gap:
                chunk=dst.read(min(CHUNK,gap))
                if not chunk or chunk.strip(b'\0'):
                    raise ValueError('Nonzero/truncated alignment gap')
                full.update(chunk);gap-=len(chunk)
            src.seek(row['offset'])
            oldhash,newhash=hashlib.sha256(),hashlib.sha256()
            def compare(chunk):
                actual=dst.read(len(chunk))
                if actual!=chunk:
                    raise ValueError('Regenerated byte differs in '+row['name']+' at '+str(dst.tell()-len(actual)))
                newhash.update(chunk);full.update(chunk)
            if row['name']=='experts':
                for index in range(LAYERS*EXPERTS):
                    chunk=src.read(BLOB)
                    if len(chunk)!=BLOB:
                        raise ValueError('Truncated original expert')
                    oldhash.update(chunk)
                    packed=pack_nvfp4_blob(chunk)
                    if pack_nvfp4_blob(packed,inverse=True)!=chunk:
                        raise ValueError('Expert inverse differs at '+str(index))
                    compare(packed)
                    if (index+1)%EXPERTS==0:
                        progress('regenerated '+str((index+1)//EXPERTS)+'/'+str(LAYERS)+' expert layers, exact bytes/inverse')
            else:
                left=row['bytes']
                while left:
                    chunk=src.read(min(CHUNK,left))
                    if not chunk:
                        raise ValueError('Truncated original section')
                    oldhash.update(chunk);left-=len(chunk)
                    if row['name'] not in replacements:
                        compare(chunk)
                if row['name'] in replacements:
                    compare(replacements[row['name']])
            if oldhash.hexdigest()!=row['sha256']:
                raise ValueError('Original archive section SHA differs: '+row['name'])
            new['sha256']=newhash.hexdigest()
            generated.append(new)
            previous=row['offset']+new['bytes']
            progress('section '+row['name']+' originalSHA/generatedSHA/targetbytes exact')
        updated=bytearray(raw)
        struct.pack_into('<8sI',updated,0,MAGIC,VERSION)
        struct.pack_into('<Q',updated,16,info['target_bytes'])
        for index,row in enumerate(generated):
            struct.pack_into('<64sQQ32s',updated,64+128*index,row['name'].encode(),row['offset'],row['bytes'],bytes.fromhex(row['sha256']))
        if actual_header!=updated or dst.tell()!=info['target_bytes'] or dst.read(1):
            raise ValueError('Generated header or final length differs')
    if identity(source)!=before_source or identity(target)!=before_target:
        raise ValueError('Source or target identity changed during verification')
    return dict(verified=True,generated_bytes_equal_target=True,sha256=full.hexdigest(),bytes=info['target_bytes'],
                source_kind='archived original NVFP4 container with inherited auxiliary sections',
                raw_checkpoint_only_reproduction=False,experts_inverse_exact=True,sections=generated)


def main():
    parser=argparse.ArgumentParser(__doc__)
    parser.add_argument('--source',type=Path,required=True)
    parser.add_argument('--target',type=Path,required=True)
    parser.add_argument('--receipt',type=Path,required=True)
    parser.add_argument('--progress-log',type=Path)
    args=parser.parse_args()
    if args.source.resolve()==args.target.resolve() or args.receipt.exists():
        parser.error('Distinct immutable source/target and a fresh receipt are required')
    def progress(message):
        line=datetime.datetime.now(datetime.timezone.utc).isoformat()+' doing=slpack archive reproduction; latest='+message+'; next=remaining bytes/header/fullSHA'
        print(line,flush=True)
        if args.progress_log:
            with args.progress_log.open('a',encoding='utf8') as stream:stream.write(line+'\n')
    report=verify(args.source,args.target,progress)
    with args.receipt.open('x',encoding='utf8') as stream:json.dump(report,stream,indent=2);stream.write('\n')
    progress('PASS '+str(report['bytes'])+'bytes SHA256 '+report['sha256'])


if __name__=='__main__':
    main()
